CREATE OR REPLACE FUNCTION "public"."fn_accept_invite"("p_token" "text") RETURNS "uuid"
    LANGUAGE "plpgsql" SECURITY DEFINER
    SET "search_path" TO 'public', 'pg_temp'
    AS $$
DECLARE
  v_user_id UUID;
  v_invite RECORD;
BEGIN
  v_user_id := auth.uid();
  IF v_user_id IS NULL THEN
    RAISE EXCEPTION 'Not authenticated' USING ERRCODE = '42501';
  END IF;

  SELECT *
  INTO v_invite
  FROM family_invites
  WHERE token = p_token
    AND accepted_at IS NULL
    AND expires_at > now()
  FOR UPDATE;

  IF NOT FOUND THEN
    RAISE EXCEPTION 'Invite not found, already accepted, or expired'
      USING ERRCODE = '22023';
  END IF;

  IF EXISTS (
    SELECT 1 FROM family_members
    WHERE family_id = v_invite.family_id AND user_id = v_user_id
  ) THEN
    UPDATE family_invites SET accepted_at = now() WHERE token = p_token;
    RETURN v_invite.family_id;
  END IF;

  INSERT INTO family_members (family_id, user_id, role)
  VALUES (v_invite.family_id, v_user_id, v_invite.role);

  UPDATE family_invites SET accepted_at = now() WHERE token = p_token;

  RETURN v_invite.family_id;
END;
$$;


