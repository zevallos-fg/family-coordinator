CREATE OR REPLACE FUNCTION "public"."fn_ingredient_fuzzy_search"("p_family_id" "uuid", "p_name" "text", "p_threshold" numeric DEFAULT 0.6) RETURNS TABLE("id" "uuid", "canonical_name" "text", "sim" numeric)
    LANGUAGE "plpgsql" STABLE SECURITY DEFINER
    SET "search_path" TO 'public', 'pg_temp'
    AS $$
begin
  -- SECURITY DEFINER bypasses RLS, so the membership check has to be explicit.
  -- Same guard fn_skill_get_monthly_spend already used; this one was missing it,
  -- which let any signed-in user read any family's ingredient list by passing
  -- that family's id.
  if not fn_user_in_family(p_family_id) then
    raise exception 'unauthorized: caller is not a member of family %', p_family_id
      using errcode = 'insufficient_privilege';
  end if;

  return query
    select i.id, i.canonical_name, similarity(i.canonical_name, p_name) as sim
      from ingredients i
     where i.family_id = p_family_id
       and i.canonical_name % p_name
       and similarity(i.canonical_name, p_name) >= p_threshold
     order by sim desc
     limit 1;
end $$;


