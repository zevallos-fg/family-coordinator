-- =====================================================================
-- BASELINE: the whole of production's public schema, as of 2026-09-07.
--
-- Why this file exists, and why it is a squash rather than a history:
--
-- Until today this repository could not rebuild the database. Not "was
-- missing a migration" — could not rebuild it at all. Production has 57
-- tables and NONE of them were created by anything in this repo. `git log`
-- confirms no migration file creating `families`, `users`, `kids`,
-- `recipes` or `baby_events` has ever been committed. The ten files that
-- were here were all deltas: ALTERs, backfills and function replacements
-- against a schema that existed only on the server.
--
-- So there was nothing to repair by writing the three missing ledger
-- entries. Replay from an empty database would have failed on the first
-- statement of the first file, because the tables it alters were never
-- created by anything replayable. The missing piece was the genesis, and
-- the only honest source for it is production itself.
--
-- This file was therefore generated by `supabase db dump --schema public`
-- against pmficrajnyeuworrqytn and is schema only: zero INSERT and zero
-- COPY statements, so no family data left production to get here.
--
-- The ten superseded delta files are kept under migrations/archive/ for
-- provenance. They are not replayed and must not be moved back; see
-- migrations/README.md.
--
-- PROVEN, not assumed: this file was replayed into an empty Postgres 17
-- and the result diffed against production. See docs/MIGRATION-REPAIR.md
-- for the diff. A migration history that has never been replayed is a
-- claim, not a backup.
-- =====================================================================

-- Production has pg_trgm installed in `public`, not the usual `extensions`
-- schema, and four GIN indexes plus fn_memory_search depend on
-- public.gin_trgm_ops resolving. Installing it anywhere else rebuilds a
-- database that looks right and cannot create its own indexes.
CREATE EXTENSION IF NOT EXISTS "pg_trgm" WITH SCHEMA "public";


-- ---------------------------------------------------------------------
-- Neutralise ambient default privileges before creating anything.
--
-- `pg_dump` emits GRANTs but never REVOKEs, because it assumes it is
-- restoring into a virgin database where no privilege exists until it is
-- granted. On Supabase that assumption is false: `postgres` carries
-- ALTER DEFAULT PRIVILEGES granting ALL on tables, functions and
-- sequences to anon, authenticated and service_role, so every object this
-- file creates is granted ALL the instant it exists — and the dump's own
-- narrower GRANT is then a no-op that can only add, never subtract.
--
-- Restoring without this block produced a database MORE permissive than
-- production in exactly the places that matter: `authenticated` gained
-- TRUNCATE on baby_events, memory_facts, reminder_log and deleted_items,
-- and `anon` gained EXECUTE on fn_accept_invite, fn_skill_record_usage
-- and fn_skill_get_monthly_spend — the last two of which spend money.
--
-- Those nine tables and twenty functions are precisely the objects
-- created by the four migrations applied through MCP, which set their
-- grants explicitly rather than inheriting the ambient ALL. A restore
-- that quietly widened them would have looked completely clean: same
-- tables, same columns, same policies, same row counts.
--
-- So: start from nothing, let the dump's explicit GRANTs be the only
-- source of privilege, and let the dump's own trailing ALTER DEFAULT
-- PRIVILEGES restore the ambient defaults for objects created later.
-- ---------------------------------------------------------------------
ALTER DEFAULT PRIVILEGES FOR ROLE "postgres" IN SCHEMA "public"
  REVOKE ALL ON TABLES FROM "anon", "authenticated", "service_role";
ALTER DEFAULT PRIVILEGES FOR ROLE "postgres" IN SCHEMA "public"
  REVOKE ALL ON FUNCTIONS FROM "anon", "authenticated", "service_role";
ALTER DEFAULT PRIVILEGES FOR ROLE "postgres" IN SCHEMA "public"
  REVOKE ALL ON SEQUENCES FROM "anon", "authenticated", "service_role";




