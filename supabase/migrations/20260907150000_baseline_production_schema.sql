-- Storage: the family-documents bucket and its policies.
--
-- `db dump --schema public` cannot see these — the bucket is a row in
-- storage.buckets and the policies sit on storage.objects — so a baseline
-- built from that dump alone would restore a database in which every
-- document upload fails. Carried forward verbatim from the superseded
-- 20260425_v34_family_documents_bucket.sql, and verified against
-- production's pg_policies.
-- =====================================================================

SELECT pg_catalog.set_config('search_path', 'public', false);

INSERT INTO storage.buckets (id, name, public, file_size_limit, allowed_mime_types)
VALUES (
  'family-documents',
  'family-documents',
  false,
  26214400,
  ARRAY[
    'application/pdf',
    'image/jpeg',
    'image/png',
    'image/heic',
    'image/webp',
    'application/vnd.openxmlformats-officedocument.wordprocessingml.document',
    'text/plain'
  ]
)
ON CONFLICT (id) DO NOTHING;

CREATE POLICY "family_documents_read" ON storage.objects FOR SELECT USING (
  bucket_id = 'family-documents'
  AND (storage.foldername(name))[1] IN (
    SELECT family_id::text FROM public.family_members WHERE user_id = auth.uid()
  )
);

CREATE POLICY "family_documents_insert" ON storage.objects FOR INSERT WITH CHECK (
  bucket_id = 'family-documents'
  AND (storage.foldername(name))[1] IN (
    SELECT family_id::text FROM public.family_members WHERE user_id = auth.uid()
  )
);

CREATE POLICY "family_documents_update" ON storage.objects FOR UPDATE USING (
  bucket_id = 'family-documents'
  AND (storage.foldername(name))[1] IN (
    SELECT family_id::text FROM public.family_members WHERE user_id = auth.uid()
  )
);

CREATE POLICY "family_documents_delete" ON storage.objects FOR DELETE USING (
  bucket_id = 'family-documents'
