CREATE OR REPLACE FUNCTION "public"."fn_baby_toggle"("p_family_id" "uuid", "p_event_type" "text", "p_kid_id" "uuid" DEFAULT NULL::"uuid", "p_payload" "jsonb" DEFAULT '{}'::"jsonb", "p_at" timestamp with time zone DEFAULT "now"()) RETURNS TABLE("id" "uuid", "event_type" "text", "started_at" timestamp with time zone, "ended_at" timestamp with time zone, "state" "text")
    LANGUAGE "plpgsql"
    SET "search_path" TO 'public', 'pg_temp'
    AS $$
declare open_id uuid;
begin
  -- ONE TAP. If a timer of this type is running, stop it; otherwise start one.
  -- No form, no modal, no decision. This is the whole one-touch principle.
  select e.id into open_id
    from public.baby_events e
   where e.family_id = p_family_id and e.event_type = p_event_type
     and (p_kid_id is null or e.kid_id = p_kid_id)
     and e.ended_at is null
   order by e.started_at desc limit 1;

  if open_id is not null then
    update public.baby_events e set ended_at = p_at where e.id = open_id;
    return query select e.id, e.event_type, e.started_at, e.ended_at, 'stopped'::text
                   from public.baby_events e where e.id = open_id;
  else
    insert into public.baby_events (family_id, kid_id, event_type, started_at, payload,
                                    logged_by_user_id, written_by)
    values (p_family_id, p_kid_id, p_event_type, p_at, coalesce(p_payload,'{}'::jsonb),
            auth.uid(), 'app')
    returning baby_events.id into open_id;
    return query select e.id, e.event_type, e.started_at, e.ended_at, 'started'::text
                   from public.baby_events e where e.id = open_id;
  end if;
end $$;


