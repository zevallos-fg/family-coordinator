CREATE OR REPLACE VIEW "public"."v_baby_today" WITH ("security_invoker"='true') AS
 WITH "win" AS (
         SELECT "f"."id" AS "family_id",
            (("date_trunc"('day'::"text", (("now"() AT TIME ZONE "f"."timezone") - ("f"."day_start_time")::interval)) + ("f"."day_start_time")::interval) AT TIME ZONE "f"."timezone") AS "day_start"
           FROM "public"."families" "f"
        ), "ev" AS (
         SELECT "e"."family_id",
            "e"."kid_id",
            "e"."event_type",
            "e"."started_at",
            "e"."ended_at",
            "w"."day_start",
            ("w"."day_start" + '1 day'::interval) AS "day_end",
            ("e"."event_type" = ANY (ARRAY['sleep'::"text", 'feed'::"text", 'pump'::"text", 'contraction'::"text"])) AS "is_timer",
                CASE
                    WHEN ("e"."event_type" = ANY (ARRAY['sleep'::"text", 'feed'::"text", 'pump'::"text", 'contraction'::"text"])) THEN COALESCE("e"."ended_at", "now"())
                    ELSE "e"."started_at"
                END AS "effective_end"
           FROM ("public"."baby_events" "e"
             JOIN "win" "w" ON (("w"."family_id" = "e"."family_id")))
        )
 SELECT "family_id",
    "kid_id",
    "event_type",
    "max"("started_at") AS "last_at",
    "count"(*) AS "count_today",
    "count"(*) FILTER (WHERE ("is_timer" AND ("ended_at" IS NULL))) AS "in_progress",
    ("sum"((EXTRACT(epoch FROM (LEAST("effective_end", "day_end") - GREATEST("started_at", "day_start"))) / (60)::numeric)))::integer AS "total_minutes"
   FROM "ev"
  WHERE (("started_at" < "day_end") AND ("effective_end" >= "day_start"))
  GROUP BY "family_id", "kid_id", "event_type";


