CREATE OR REPLACE FUNCTION "public"."fn_memory_recall"("target_family_id" "uuid", "p_query" "text", "p_limit" integer DEFAULT 20) RETURNS TABLE("kind" "text", "subject" "text", "statement" "text", "detail" "text", "as_of" timestamp with time zone, "needs_attention" boolean, "source_table" "text", "source_id" "uuid", "score" real)
    LANGUAGE "sql" STABLE
    SET "search_path" TO 'public', 'pg_temp'
    AS $$
  select m.kind, m.subject, m.statement, m.detail, m.as_of,
         m.needs_attention, m.source_table, m.source_id,
         greatest(
           public.similarity(coalesce(m.subject, ''), p_query),
           public.similarity(coalesce(m.statement, ''), p_query),
           public.similarity(coalesce(m.detail, ''), p_query)
         ) as score
    from public.v_family_memory m
   where m.family_id = target_family_id
     and ( coalesce(m.subject, '') ilike '%' || p_query || '%'
        or coalesce(m.statement, '') ilike '%' || p_query || '%'
        or coalesce(m.detail, '') ilike '%' || p_query || '%'
        or public.similarity(coalesce(m.subject, ''), p_query) > 0.25
        or public.similarity(coalesce(m.statement, ''), p_query) > 0.25 )
   order by score desc, m.as_of desc
   limit least(coalesce(p_limit, 20), 100);
$$;


